"""[4-task study] click_bell COUNTERFACTUAL SCENES (simulator reset only; no expert, no policy, no env.step except 10 settle steps).
One scene = the natural click_bell scene of `seed` (bell model m) PLUS a second bell of the OTHER model (1-m) at a separated location, + 0..3 distractors (same SPEC as the 10-task capture).
Both bells are valid referents: RoboTwin describes the bell by its model (description/objects_description/050_bell/base{0,1}.json: white/black vs blue/brown).
Per scene, for each bell i: instruction WITH arm word (info {A: 050_bell/base_m, a: arm(i)}) and instruction WITHOUT arm word (info {A}), both generated by RoboTwin's own generate_episode_descriptions (seen split).
Records: 3 camera frames (home pose, half-res) + K/E + object xyz (PRIVILEGED = LABELS ONLY) + the instruction sets. Seeds 3000000+ (disjoint from all dev/final seeds).
usage: gen_cf_bell.py N START_SEED OUTDIR"""
import sys; 
from regsp import paths as P
import os, json, pickle, numpy as np, sapien
import sapien.core as sp
_od = sapien.render.set_ray_tracing_denoiser; sapien.render.set_ray_tracing_denoiser = lambda n: _od(os.environ.get("RGL_DENOISER", "optix"))
from regsp.envs import robotwin as S
N, st, out = int(sys.argv[1]), int(sys.argv[2]), os.path.abspath(sys.argv[3]); os.makedirs(out, exist_ok=True)
from envs.utils import create_actor
from generate_episode_instructions import generate_episode_descriptions
env, args = S.make("click_bell", "demo_clean")
SPEC = {"bottle": dict(modelname="001_bottle", ids=[13, 16], qpos=[[0.707, 0, 0, -0.707], [0.707, 0, 0, 0.707]], z=0.752), "roller": dict(modelname="102_roller", ids=[0, 2], qpos=[[0.5, 0.5, 0.5, 0.5], [0, 0, 0.707, 0.707]], z=0.741), "hammer": dict(modelname="020_hammer", ids=[0], qpos=[[0, 0, 0.995, 0.105]], z=0.783),
        "cup": dict(modelname="021_cup", ids=[0], qpos=[[0.5, 0.5, 0.5, 0.5]], z=0.741), "coaster": dict(modelname="019_coaster", ids=[0], qpos=[[0.5, 0.5, 0.5, 0.5]], z=0.741)}
cams = ("head_camera", "left_camera", "right_camera")
def snap(env):
    o = env.get_obs()["observation"]; fr, K, E = {}, {}, {}
    for c in cams: fr[c] = np.ascontiguousarray(o[c]["rgb"][::2, ::2]); K[c] = np.array(o[c]["intrinsic_cv"]); E[c] = np.array(o[c]["extrinsic_cv"])
    return fr, K, E
def spawn_extra(rng, cls, taken):
    s = SPEC[cls]
    for _ in range(40):
        xy = np.array([rng.uniform(-0.32, 0.32), rng.uniform(-0.22, 0.08)])
        if all(np.hypot(*(xy - t)) > 0.14 for t in taken):
            k = rng.integers(len(s["ids"]))
            try: a = create_actor(scene=env, pose=sp.Pose([xy[0], xy[1], s["z"]], s["qpos"][k]), modelname=s["modelname"], convex=True, model_id=s["ids"][k], is_static=False); return a, xy
            except Exception: return None, None
    return None, None
def instr(info, rng, n=30):
    d = generate_episode_descriptions("click_bell", [info], n)[0]["seen"]; return str(d[rng.integers(len(d))])
done = 0; seed = st; tries = 0
while done < N and tries < 3 * N:
    tries += 1; f = f"{out}/cf{seed}.pkl"
    if os.path.exists(f) and os.path.exists(f.replace(".pkl", ".npz")): done += 1; seed += 1; continue
    af = f"{out}/att{seed}.txt"; na = int(open(af).read()) if os.path.exists(af) else 0
    if na >= 2: seed += 1; continue
    open(af, "w").write(str(na + 1))
    try:
        with S.Quiet():
            env.setup_demo(now_ep_num=done, seed=seed, is_test=True, **args); rng = np.random.default_rng(seed + 17)
            m = int(env.bell_id); p1 = np.array(env.bell.get_pose().p); taken = [p1[:2]]; p2 = None
            for _ in range(200):
                x, y = rng.uniform(-0.25, 0.25), rng.uniform(-0.2, 0.0)
                if abs(x) >= 0.05 and np.hypot(*(np.array([x, y]) - p1[:2])) >= 0.14 and abs(x - p1[0]) >= 0.06: p2 = np.array([x, y, p1[2]]); break
            if p2 is None: raise RuntimeError("no_second_bell_pose")
            b2 = create_actor(scene=env, pose=sp.Pose(p2.tolist(), [0.5, 0.5, 0.5, 0.5]), modelname="050_bell", convex=True, model_id=1 - m, is_static=True); taken.append(p2[:2])
            extra = list(rng.choice(list(SPEC), size=int(rng.integers(0, 4)), replace=False)); EX = []
            for c in extra:
                a, xy = spawn_extra(rng, c, taken)
                if a is not None: taken.append(xy); a.set_name(SPEC[c]["modelname"]); EX.append(a)
            for _ in range(10): env.scene.step()
            bells = [{"attr": "bell", "model": m, "xyz": np.array(env.bell.get_pose().p).tolist()}, {"attr": "bell2", "model": 1 - m, "xyz": np.array(b2.get_pose().p).tolist()}]
            for b in bells: b["arm"] = "right" if b["xyz"][0] > 0 else "left"; b["instr_arm"] = instr({"{A}": f"050_bell/base{b['model']}", "{a}": b["arm"]}, rng); b["instr_noarm"] = instr({"{A}": f"050_bell/base{b['model']}"}, rng)
            objects = bells[:] + [{"attr": f"extra{i}", "model": None, "xyz": np.array(a.get_pose().p).tolist(), "name": a.get_name()} for i, a in enumerate(EX)]
            fr, K, E = snap(env); env.close_env()
    except Exception as e:
        try: env.close_env()
        except Exception: pass
        print("cf fail", seed, type(e).__name__, str(e)[:100], flush=True)
        if any(x in str(e) for x in ("DeviceLost", "vk::", "Vulkan", "out of memory")): os._exit(3)
        seed += 1; continue
    pickle.dump({"task": "click_bell", "seed": seed, "bells": bells, "objects": objects, "K": K, "E": E, "n_extra": len(EX)}, open(f, "wb")); np.savez_compressed(f.replace(".pkl", ".npz"), **{c: fr[c] for c in cams})
    done += 1; print("click_bell cf", done, N, seed, [(b["model"], b["arm"]) for b in bells], flush=True); seed += 1
open(out + "/DONE", "w").write("ok")
